class AnomalyEvent(Base):
    """
    Time-series metric anomaly detected by statistical or machine-learning detectors.
    """
    __tablename__ = "anomaly_events"
    __table_args__ = (
        Index("ix_anomalies_org_detected", "organization_id", "detected_at"),
        Index("ix_anomalies_svc_metric", "service_id", "metric_name"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        primary_key=True,
        default=uuid.uuid4,
    )
    organization_id: Mapped[uuid.UUID] = mapped_column(
        Uuid,
        ForeignKey("organizations.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    service_id: Mapped[str] = mapped_column(
        String(100),
        ForeignKey("services.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    service_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
    )
    metric_name: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
    )  # cpu_percent, memory_percent, latency_ms, error_rate, disk_percent
    current_value: Mapped[float] = mapped_column(
        Float,
        nullable=False,
    )
    baseline_value: Mapped[float] = mapped_column(
        Float,
        nullable=False,
    )
    z_score: Mapped[float] = mapped_column(
        Float,
        default=0.0,
        nullable=False,
    )
    anomaly_score: Mapped[float] = mapped_column(
        Float,
        default=0.0,
        nullable=False,
    )  # 0.0 to 1.0
    severity: Mapped[str] = mapped_column(
        String(50),
        default="medium",
        nullable=False,
    )  # informational, low, medium, high, critical
    status: Mapped[str] = mapped_column(
        String(50),
        default="detected",
        nullable=False,
    )  # detected, correlated, resolved, suppressed
    details: Mapped[str] = mapped_column(
        Text,
        default="",
        nullable=False,
    )
    detected_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=utc_now,
        index=True,
        nullable=False,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=utc_now,
        nullable=False,
    )

    # Relationships
    organization: Mapped["Organization"] = relationship("Organization")
    service: Mapped["Service"] = relationship("Service")


